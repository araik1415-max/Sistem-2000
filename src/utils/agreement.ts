/**
 * Проверка, увеличивает ли данный способ оплаты депозитный баланс
 */
export function isPaymentMethodDepositEligible(method: string): boolean {
  const depositEligibleMethods = ['dram', 'cash', 'card', 'idram', 'telcell', 'arca', 'visa', 'mastercard', 'external_payment'];
  return depositEligibleMethods.includes(method.toLowerCase());
}

/**
 * Проверка, квалифицируется ли покупка для пожизненного депозита (от 10 000 ֏)
 */
export function qualifiesForLifelongDeposit(amountDram: number, paymentMethod: string): boolean {
  return amountDram >= MIN_PURCHASE_FOR_DEPOSIT && isPaymentMethodDepositEligible(paymentMethod);
}

